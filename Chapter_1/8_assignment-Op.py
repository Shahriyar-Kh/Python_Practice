#Assignment Operators in Python
#Assignment operators are used to assign values to variables. In python, we have several assignment operators that can be used to perform different operations on the variables. The most common assignment operator is the equal sign (=) which is used to assign a value to a variable. For example, x = 10 assigns the value 10 to the variable x.

print("*********************** 1. using = operator for assignment *****************")
#using = operator for assignment
x=10
print(x)

x+=5 #x=x+5
print(x)
x-=3 #x=x-3
print(x)
x*=2 #x=x*2
print(x)
x/=4 #x=x/4
print(x)
x//=2 #x=x//2
print(x)
x%=3 #x=x%3
print(x)
x**=2 #x=x**2
print(x)
