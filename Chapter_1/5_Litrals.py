#Litral is a fixed value that is assigned to a variable. It can be of different data types such as integer, float, string, boolean, etc. In python, we can use literals to represent values in our code.

#integer literal
print("*********************** 1. Integer literals *****************")
a=10
print(a)
#float literal
print("*********************** 2. Float literals *****************")
b=10.5
print(b)

#string literal
print("*********************** 3. String literals *****************")
c="Shahriyar Khan"
print(c)

#boolean literal
print("*********************** 4. Boolean literals *****************")
d=True
print(d)

